let LANG = "pt-BR";

function detectLang() {
  const nav = (navigator.language || "pt-BR").toLowerCase();
  if (nav.startsWith("pt")) return "pt-BR";
  if (nav.startsWith("es")) return "es";
  if (nav.startsWith("en")) return "en";
  return "pt-BR";
}

function setLang(lang) {
  LANG = LANGS.includes(lang) ? lang : "pt-BR";
  document.documentElement.lang = LANG;
}

// t("chave", { variavel: valor })
function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N["pt-BR"][key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}

// Aplica as traduções nos elementos marcados no HTML.
function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", t(el.dataset.i18nTitle));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-prompt]").forEach(el => { el.dataset.prompt = t(el.dataset.i18nPrompt); });
}
